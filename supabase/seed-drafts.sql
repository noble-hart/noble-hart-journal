"Game night in five minutes, everybody downstairs!" sounds like an order. Try asking earlier and more casually: "We''re thinking of doing a quick game Saturday after dinner. Want in?" Giving a heads-up and a choice makes a big difference. Most teens would rather say yes than be told.

2. Give them a job

People join in faster when they have a role. Ask your teen to pick the first game, be the scorekeeper, choose the snacks or run the playlist. It turns them from a guest into a host. And a host is much less likely to wander off.

3. Deal with phones early

Don''t fight a battle you''ll lose. Agree on a simple rule before you start: phones in a basket for the length of the game, or only out for the score. Make it apply to adults too. If everyone does it, it doesn''t feel like a punishment.

