If you''re playing trivia or a team game, split people up by mixing ages. Put a teen with a grandparent, or a parent with a cousin. They''ll remember things the others don''t, and you''ll hear some surprising answers. Teams also take the pressure off any one person.

6. Keep the stakes silly

A prize helps, as long as it''s small and funny. A paper crown for the winner. Choosing the next movie. Skipping one chore. Avoid anything serious. The point is a little friendly rivalry, not a fight.

