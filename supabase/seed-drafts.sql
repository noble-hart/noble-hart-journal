They''re easy to answer

A blank question like "Tell us something about yourself" is hard. You have to think of something, decide whether it''s interesting enough and hope you don''t sound boring. A would-you-rather hands you two options. All you have to do is pick one. That''s a much smaller ask, and small asks get said yes to.

There''s no wrong answer

Nobody is being tested. There''s no correct choice, so nobody can fail. That matters most for quiet people and for teens, who tend to avoid anything where they might look foolish.

The "why" is where the good stuff is

The pick is just the starting point. The real conversation begins when someone says, "Wait, why would you choose that?" Suddenly you''re hearing how your aunt thinks, or what your teenager would actually do in a ridiculous situation. You learn about people without anybody feeling interrogated.

Humor lowers the guard

When the options are silly, people relax. Laughing together breaks the stiff, formal feeling that sometimes sits on a family gathering. Once everyone has laughed once, the next question is easier.

What makes a good question

Not every question works. The best ones tend to have four things:

Two options that are actually balanced. "Would you rather be rich or broke?" isn''t a dilemma, it''s a giveaway. Make both sides tempting or both sides terrible.

A picture you can see in your head. "Would you rather have your alarm go off with your mom''s voice shouting ''Wake up, sweetie!'' in the middle of class" works because you can imagine it.

A light touch. Keep it fun, not heavy. Skip anything about money trouble, family conflict or people''s bodies.

Room for jokes. The best questions invite people to argue and tease, kindly.

How to run a round

Read the question out loud. Slowly, with a little drama.

Give everyone a few seconds to think.

Go around the table. Everyone picks one, and everyone gives a one-sentence reason.

